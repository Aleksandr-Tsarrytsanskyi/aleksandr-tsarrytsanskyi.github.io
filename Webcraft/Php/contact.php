<?php

header(
    'Content-Type: application/json; charset=utf-8'
);

require_once __DIR__ . '/db.php';
require_once __DIR__ . '/telegram.php';


/*
|--------------------------------------------------------------------------
| JSON response
|--------------------------------------------------------------------------
*/

function response(
    bool $success,
    string $message,
    int $status = 200,
    array $data = []
): never {

    http_response_code($status);

    echo json_encode(
        array_merge(
            [
                'success' => $success,
                'message' => $message
            ],
            $data
        ),
        JSON_UNESCAPED_UNICODE
    );

    exit;
}


/*
|--------------------------------------------------------------------------
| Только POST
|--------------------------------------------------------------------------
*/

if (
    ($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST'
) {

    response(
        false,
        'Метод запроса недоступен.',
        405
    );
}


/*
|--------------------------------------------------------------------------
| Получаем данные
|--------------------------------------------------------------------------
*/

$name = trim(
    (string)($_POST['name'] ?? '')
);

$email = trim(
    (string)($_POST['email'] ?? '')
);

$telegram = trim(
    (string)($_POST['telegram'] ?? '')
);

$message = trim(
    (string)($_POST['message'] ?? '')
);

$privacy =
    isset($_POST['privacy']) &&
    $_POST['privacy'] === '1';


/*
|--------------------------------------------------------------------------
| Имя
|--------------------------------------------------------------------------
*/

if (
    mb_strlen($name) < 2 ||
    mb_strlen($name) > 100
) {

    response(
        false,
        'Введите корректное имя.',
        422
    );
}


/*
|--------------------------------------------------------------------------
| Email
|--------------------------------------------------------------------------
*/

if (
    !filter_var(
        $email,
        FILTER_VALIDATE_EMAIL
    )
) {

    response(
        false,
        'Введите корректный Email.',
        422
    );
}


/*
|--------------------------------------------------------------------------
| Telegram
|--------------------------------------------------------------------------
|
| Telegram обязательный.
|
| Формат:
| @username
|
|--------------------------------------------------------------------------
*/

if (
    !preg_match(
        '/^@[a-zA-Z0-9_]{3,32}$/',
        $telegram
    )
) {

    response(
        false,
        'Введите корректный Telegram в формате @username.',
        422
    );
}


/*
|--------------------------------------------------------------------------
| Сообщение
|--------------------------------------------------------------------------
*/

if (
    mb_strlen($message) < 5 ||
    mb_strlen($message) > 5000
) {

    response(
        false,
        'Введите сообщение от 5 до 5000 символов.',
        422
    );
}


/*
|--------------------------------------------------------------------------
| Согласие
|--------------------------------------------------------------------------
*/

if (!$privacy) {

    response(
        false,
        'Необходимо согласиться на обработку персональных данных.',
        422
    );
}


/*
|--------------------------------------------------------------------------
| Сохраняем заявку в БД
|--------------------------------------------------------------------------
*/

try {

    $stmt = $pdo->prepare("
        INSERT INTO contact_requests (
            name,
            email,
            telegram,
            message,
            privacy
        )
        VALUES (
            :name,
            :email,
            :telegram,
            :message,
            :privacy
        )
    ");


    $stmt->execute([

        ':name' =>
            $name,

        ':email' =>
            $email,

        ':telegram' =>
            $telegram,

        ':message' =>
            $message,

        ':privacy' =>
            1
    ]);


    /*
     * ID созданной заявки
     */

    $requestId =
        (int)$pdo->lastInsertId();


    if ($requestId <= 0) {

        throw new RuntimeException(
            'Не удалось получить ID заявки.'
        );
    }


} catch (Throwable $error) {

    error_log(
        'Contact DB error: ' .
        $error->getMessage()
    );


    response(
        false,
        'Не удалось сохранить сообщение.',
        500
    );
}


/*
|--------------------------------------------------------------------------
| Telegram
|--------------------------------------------------------------------------
|
| ВАЖНО:
|
| Заявка уже находится в БД.
|
| Ошибка Telegram НЕ отменяет заявку.
|
|--------------------------------------------------------------------------
*/

try {

    sendTelegramMessage([

        'type' =>
            'contact',

        'id' =>
            $requestId,

        'name' =>
            $name,

        'email' =>
            $email,

        'telegram' =>
            $telegram,

        'message' =>
            $message

    ]);

} catch (Throwable $error) {

    /*
     * Telegram не отправил сообщение.
     *
     * Заявка всё равно считается успешной.
     */

    error_log(
        'Contact Telegram error: ' .
        $error->getMessage()
    );
}


/*
|--------------------------------------------------------------------------
| УСПЕШНЫЙ ОТВЕТ
|--------------------------------------------------------------------------
*/

response(
    true,
    'Сообщение успешно отправлено.',
    200,
    [
        'id' => $requestId
    ]
);

